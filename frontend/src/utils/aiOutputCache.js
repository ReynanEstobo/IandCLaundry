// Gemini results are cached per filter in this browser so the Gemini request
// quota is not spent each time a page opens or a new order arrives.
export const AI_CACHE_FRESH_MS = 6 * 60 * 60 * 1000 // same data as when it was generated
export const AI_CACHE_REUSE_MS = 60 * 60 * 1000 // the data has changed since
export const AI_CACHE_KEEP_MS = 24 * 60 * 60 * 1000 // last Gemini result, shown while Gemini cannot answer

const LEGACY_PREFIXES = ['ai_forecast_v5_', 'ai_insights_v4_']
const inFlight = new Map()

// Joins an identical AI request that is already on its way instead of asking Gemini twice.
export function sharedAiRequest(key, request) {
  if (!inFlight.has(key)) inFlight.set(key, Promise.resolve().then(request).finally(() => inFlight.delete(key)))
  return inFlight.get(key)
}

export function aiCacheKey(feature, parts) {
  return `ai_${feature}_v6:${parts.map(part => part ?? '').join(':')}`
}

// Short fingerprint of the data a result was generated from.
export function dataFingerprint(value) {
  const text = typeof value === 'string' ? value : JSON.stringify(value)
  let hash = 5381
  for (let index = 0; index < text.length; index += 1) hash = ((hash * 33) ^ text.charCodeAt(index)) >>> 0
  return `${text.length}-${hash.toString(36)}`
}

export function readAiCache(key) {
  try {
    const entry = JSON.parse(localStorage.getItem(key))
    return entry && entry.data && Number.isFinite(entry.savedAt) ? entry : null
  } catch {
    return null
  }
}

export function writeAiCache(key, entry) {
  try {
    localStorage.setItem(key, JSON.stringify(entry))
  } catch {
    // Storage can be full or blocked; the result is still shown, just not kept.
  }
}

// A cached Gemini result that can be shown instead of asking Gemini again.
export function reusableAiCache(entry, dataVersion, now = Date.now()) {
  if (!entry) return null
  const age = now - entry.savedAt
  if (age < 0) return null
  return age < (entry.dataVersion === dataVersion ? AI_CACHE_FRESH_MS : AI_CACHE_REUSE_MS) ? entry : null
}

// The last Gemini result, kept to show (with the reason) when Gemini cannot answer now.
export function lastGeminiResult(entry, now = Date.now()) {
  return entry && now - entry.savedAt >= 0 && now - entry.savedAt < AI_CACHE_KEEP_MS ? entry : null
}

export function pruneLegacyAiCache() {
  try {
    for (let index = localStorage.length - 1; index >= 0; index -= 1) {
      const key = localStorage.key(index)
      if (key && LEGACY_PREFIXES.some(prefix => key.startsWith(prefix))) localStorage.removeItem(key)
    }
  } catch {
    // Nothing to clean up when storage is unavailable.
  }
}

export function geminiModelLabel(model) {
  return String(model || '').replace(/^gemini-/, 'Gemini ').replace(/-lite$/, '-Lite').replace(/-flash/, ' Flash').replace(/-pro/, ' Pro')
}

// Why the AI request itself failed (before Gemini was even asked).
export function aiServiceErrorReason(error) {
  const status = error?.response?.status
  if (status === 429) return 'Too many AI requests from this account right now. Try again in a few minutes.'
  if (status === 401 || status === 403) return 'This session cannot use AI features. Sign in again as an administrator.'
  return `The AI service could not be reached (${error?.message || 'network error'}).`
}

// One plain sentence naming where an AI output came from, and why when it is not fresh Gemini output.
export function describeAiSource(meta) {
  if (meta?.source === 'gemini') {
    const model = geminiModelLabel(meta.model) || 'Gemini'
    if (meta.reason) return `Last Gemini AI result (${model}); Gemini could not refresh it: ${meta.reason}`
    return `${meta.isCached ? 'Cached Gemini AI result' : 'Generated by Gemini AI'} (${model})${meta.staleData ? ', made before the latest records' : ''}`
  }
  if (meta?.source === 'baseline') return `Local baseline, not Gemini AI. Reason: ${meta.reason || 'Gemini did not return a result.'}`
  return 'Preparing AI output'
}
